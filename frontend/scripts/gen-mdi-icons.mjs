// Regenerates src/plugins/mdi-icons.ts.
//
// Scans the app for every `mdi-*` icon name (templates, props, constants) and
// maps each to its @mdi/js SVG path, so the Vuetify custom icon set can render
// SVGs instead of shipping the full MDI webfont. Tree-shaking keeps only the
// icons actually used.
//
// Run: pnpm --filter frontend icons:gen
import * as mdi from '@mdi/js';
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// Exclude this feature's own config files: vuetify.ts mentions the "mdi-svg"
// iconset and the generated map references "gen-mdi-icons" — neither is a real
// icon usage. execFileSync (no shell) keeps the glob args intact on Windows.
const raw = execFileSync(
  'rg',
  [
    '-o',
    '-I',
    '-N',
    'mdi-[a-z0-9-]+',
    'src',
    '-g',
    '!src/plugins/mdi-icons.ts',
    '-g',
    '!src/plugins/vuetify.ts',
  ],
  { cwd: root, encoding: 'utf8' },
);
const names = [...new Set(raw.split('\n').map((s) => s.trim()).filter(Boolean))].sort();

const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const toExport = (n) => {
  const parts = n.split('-');
  return parts[0] + parts.slice(1).map(cap).join('');
};

const ok = [];
const missing = [];
for (const name of names) {
  const exp = toExport(name);
  if (mdi[exp] !== undefined) ok.push([name, exp]);
  else missing.push([name, exp]);
}
ok.sort((a, b) => (a[0] < b[0] ? -1 : 1));

const exports = [...new Set(ok.map(([, exp]) => exp))].sort();
const out =
  '// AUTO-GENERATED by scripts/gen-mdi-icons.mjs — do not edit by hand.\n' +
  '// Maps every kebab-case MDI name used in the app to its @mdi/js SVG path so\n' +
  '// the Vuetify custom icon set (plugins/vuetify.ts) renders SVGs instead of\n' +
  '// shipping the full MDI webfont. Regenerate: pnpm --filter frontend icons:gen\n\n' +
  'import {\n' +
  exports.map((exp) => `  ${exp},`).join('\n') +
  "\n} from '@mdi/js';\n\n" +
  'export const mdiIconPaths: Record<string, string> = {\n' +
  ok.map(([name, exp]) => `  '${name}': ${exp},`).join('\n') +
  '\n};\n';

fs.writeFileSync(path.join(root, 'src/plugins/mdi-icons.ts'), out);
console.log(`generated ${ok.length} icons; missing ${missing.length}`);
if (missing.length) {
  console.log('MISSING (not found in @mdi/js):', missing.map((m) => m[0]).join(', '));
  process.exitCode = 1;
}
